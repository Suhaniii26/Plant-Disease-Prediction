import numpy as np
import matplotlib.pyplot as plt
import tensorflow as tf

DATA = "/content/processed_dataset"
SIZE = (224, 224)
BATCH = 32

train = tf.keras.utils.image_dataset_from_directory(
    DATA + "/train", image_size=SIZE, batch_size=BATCH, shuffle=True, seed=42)
val = tf.keras.utils.image_dataset_from_directory(
    DATA + "/validation", image_size=SIZE, batch_size=BATCH, shuffle=False)
test = tf.keras.utils.image_dataset_from_directory(
    DATA + "/test", image_size=SIZE, batch_size=BATCH, shuffle=False)

names = train.class_names
print(len(names), "classes")

counts = np.zeros(len(names))
for imgs, labels in train:
    for l in labels.numpy():
        counts[l] += 1

plt.figure(figsize=(16, 5))
plt.bar(range(len(names)), counts)
plt.xticks(range(len(names)), names, rotation=90)
plt.title("Images per class (train)")
plt.tight_layout()
plt.show()

plt.figure(figsize=(12, 12))
for imgs, labels in train.take(1):
    for i in range(9):
        plt.subplot(3, 3, i + 1)
        plt.imshow(imgs[i].numpy().astype("uint8"))
        plt.title(names[labels[i]], fontsize=8)
        plt.axis("off")
plt.show()

train = train.prefetch(tf.data.AUTOTUNE)
val = val.prefetch(tf.data.AUTOTUNE)
test = test.prefetch(tf.data.AUTOTUNE)

from tensorflow.keras import layers, models

model = models.Sequential([
    layers.Input(shape=(224, 224, 3)),
    layers.Rescaling(1./255),

    layers.Conv2D(32, 3, activation="relu"),
    layers.MaxPooling2D(),
    layers.Conv2D(64, 3, activation="relu"),
    layers.MaxPooling2D(),
    layers.Conv2D(128, 3, activation="relu"),
    layers.MaxPooling2D(),
    layers.Conv2D(256, 3, activation="relu"),
    layers.MaxPooling2D(),

    layers.Flatten(),
    layers.Dense(256, activation="relu"),
    layers.Dropout(0.5),
    layers.Dense(len(names), activation="softmax")
])

model.compile(optimizer="adam",
              loss="sparse_categorical_crossentropy",
              metrics=["accuracy"])
model.summary()

cb = [
    tf.keras.callbacks.EarlyStopping(patience=4, restore_best_weights=True),
    tf.keras.callbacks.ModelCheckpoint("best_model.keras", save_best_only=True)
]

hist = model.fit(train, validation_data=val, epochs=20, callbacks=cb)

from sklearn.metrics import classification_report, confusion_matrix
import seaborn as sns

plt.figure(figsize=(12, 4))
plt.subplot(1, 2, 1)
plt.plot(hist.history["accuracy"], label="train")
plt.plot(hist.history["val_accuracy"], label="val")
plt.title("Accuracy"); plt.legend()
plt.subplot(1, 2, 2)
plt.plot(hist.history["loss"], label="train")
plt.plot(hist.history["val_loss"], label="val")
plt.title("Loss"); plt.legend()
plt.show()

loss, acc = model.evaluate(test)
print("Test accuracy:", acc)

y_true = np.concatenate([y.numpy() for _, y in test])
y_pred = np.argmax(model.predict(test), axis=1)

print(classification_report(y_true, y_pred, target_names=names))

cm = confusion_matrix(y_true, y_pred)
plt.figure(figsize=(18, 16))
sns.heatmap(cm, xticklabels=names, yticklabels=names, cmap="Blues")
plt.xlabel("Predicted"); plt.ylabel("Actual")
plt.title("Confusion Matrix")
plt.show()

model.save("plant_disease_model.keras")
